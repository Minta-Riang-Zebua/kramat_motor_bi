CREATE DATABASE IF NOT EXISTS kramat_motor_bi CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE kramat_motor_bi;

CREATE TABLE IF NOT EXISTS tb_user (
    id_user INT AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    nama VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    role ENUM('admin','manajemen') NOT NULL,
    status ENUM('aktif','nonaktif') NOT NULL DEFAULT 'aktif',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS tb_produk (
    id_produk INT AUTO_INCREMENT PRIMARY KEY,
    nama_produk VARCHAR(150) NOT NULL UNIQUE,
    kategori VARCHAR(100) NOT NULL,
    status ENUM('aktif','nonaktif') NOT NULL DEFAULT 'aktif'
);

CREATE TABLE IF NOT EXISTS tb_penjualan (
    id_penjualan INT AUTO_INCREMENT PRIMARY KEY,
    id_produk INT NOT NULL,
    periode VARCHAR(30) NOT NULL,
    periode_date DATE NOT NULL,
    harga DECIMAL(15,2) NOT NULL,
    stok INT NOT NULL,
    terjual INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_penjualan_produk FOREIGN KEY (id_produk) REFERENCES tb_produk(id_produk),
    UNIQUE KEY uq_produk_periode (id_produk, periode_date)
);

CREATE TABLE IF NOT EXISTS tb_prediksi (
    id_prediksi INT AUTO_INCREMENT PRIMARY KEY,
    id_produk INT NOT NULL,
    periode_prediksi DATE NOT NULL,
    lag_1 DECIMAL(12,4) NOT NULL,
    lag_2 DECIMAL(12,4) NOT NULL,
    lag_3 DECIMAL(12,4) NOT NULL,
    harga DECIMAL(15,2) NOT NULL,
    stok INT NOT NULL,
    hasil_prediksi DECIMAL(12,4) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_prediksi_produk FOREIGN KEY (id_produk) REFERENCES tb_produk(id_produk)
);

CREATE TABLE IF NOT EXISTS tb_log_aktivitas (
    id_log BIGINT AUTO_INCREMENT PRIMARY KEY,
    id_user INT NOT NULL,
    aktivitas VARCHAR(255) NOT NULL,
    waktu TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_log_user FOREIGN KEY (id_user) REFERENCES tb_user(id_user)
);


